-- schema.sql — reference DDL for the apexvoid-trading-bot PostgreSQL database.
--
-- Authoritative creator: algo-bot/app/persistence/store.py::init_db()
-- (idempotent IF NOT EXISTS + ALTER migrations on every boot).
-- Keep this file aligned when adding tables; do not treat it as a migrator.

-- Append-only log of pips results auto-edited into the channel.
CREATE TABLE IF NOT EXISTS pips_log (
  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts         BIGINT  NOT NULL,
  sign       TEXT    NOT NULL,
  pips       INTEGER NOT NULL,
  message_id BIGINT,
  chat_id    TEXT,
  signal_id  BIGINT
);
CREATE INDEX IF NOT EXISTS idx_pips_ts        ON pips_log(ts);
CREATE INDEX IF NOT EXISTS idx_pips_signal_id ON pips_log(signal_id);

-- Lifecycle tracker for every signal posted via the bot's DM interface.
CREATE TABLE IF NOT EXISTS manual_signals (
  id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts                   BIGINT           NOT NULL,
  action               TEXT             NOT NULL,
  entry                DOUBLE PRECISION NOT NULL,
  entry_end            DOUBLE PRECISION,
  sl                   DOUBLE PRECISION NOT NULL,
  original_sl          DOUBLE PRECISION,
  tps                  TEXT             NOT NULL,
  order_type           TEXT             NOT NULL,
  channel_message_id   BIGINT,
  status               TEXT             NOT NULL DEFAULT 'open',
  result_pips          INTEGER,
  closed_at            BIGINT,
  daily_seq            INTEGER,
  trade_date           TEXT,
  fill_state           TEXT             NOT NULL DEFAULT 'pending',
  filled_at            BIGINT,
  legs                 TEXT             NOT NULL DEFAULT '[]',
  parent_id            BIGINT,
  setup_type           TEXT,
  confluence           INTEGER,
  note                 TEXT,
  symbol               TEXT             NOT NULL DEFAULT 'XAU',
  visibility           TEXT             NOT NULL DEFAULT 'both',
  algo_armed           BOOLEAN          NOT NULL DEFAULT FALSE,
  trade_stream         TEXT             NOT NULL DEFAULT 'manual',
  execution_mode       TEXT             NOT NULL DEFAULT 'notify',
  execution_status     TEXT,
  execution_intent_id  TEXT,
  execution_revision   INTEGER          NOT NULL DEFAULT 0,
  broker_position_id   TEXT,
  broker_fill_price    DOUBLE PRECISION,
  execution_error      TEXT
);
CREATE INDEX IF NOT EXISTS idx_manual_signals_status
  ON manual_signals(status);
CREATE INDEX IF NOT EXISTS idx_manual_signals_trade_date
  ON manual_signals(trade_date);
CREATE INDEX IF NOT EXISTS idx_manual_signals_symbol_trade_date
  ON manual_signals(symbol, trade_date);
CREATE INDEX IF NOT EXISTS idx_manual_signals_parent_id
  ON manual_signals(parent_id);

-- Broker fill ledger (scale-ins keep separate rows).
CREATE TABLE IF NOT EXISTS auto_trade_fills (
  position_id       BIGINT PRIMARY KEY,
  group_id          TEXT             NOT NULL,
  trade_key         TEXT             NOT NULL,
  trade_stream      TEXT             NOT NULL,
  symbol            TEXT             NOT NULL DEFAULT 'XAU',
  setup_type        TEXT,
  direction         TEXT,
  entry_price       DOUBLE PRECISION,
  stop_pips         DOUBLE PRECISION,
  volume            BIGINT,
  filled_at         BIGINT           NOT NULL,
  correction_source TEXT,
  corrected_at      BIGINT
);
CREATE INDEX IF NOT EXISTS idx_auto_trade_fills_group
  ON auto_trade_fills(group_id);

-- One closed result per execution group.
CREATE TABLE IF NOT EXISTS auto_trade_results (
  group_id          TEXT PRIMARY KEY,
  trade_key         TEXT             NOT NULL,
  trade_stream      TEXT             NOT NULL,
  result_pips       DOUBLE PRECISION NOT NULL,
  closed_at         BIGINT           NOT NULL,
  setup_type        TEXT,
  direction         TEXT,
  session           TEXT,
  killzone_name     TEXT,
  stop_pips         DOUBLE PRECISION,
  booked_tp_count   INTEGER,
  utc_hour          INTEGER,
  symbol            TEXT             NOT NULL DEFAULT 'XAU',
  correction_source TEXT,
  corrected_at      BIGINT,
  -- Volume-weighted realized pips from the executor; result_pips is the
  -- highest TP archived. NULL for rows closed before the executor sent it.
  realized_pips     DOUBLE PRECISION,
  -- Pips from the group's deepest fill to its original stop: the R denominator.
  risk_pips         DOUBLE PRECISION
);
CREATE INDEX IF NOT EXISTS idx_auto_trade_results_closed
  ON auto_trade_results(closed_at);

-- One row per delivered post (VIP / public) for a signal.
CREATE TABLE IF NOT EXISTS signal_posts (
  signal_id  BIGINT NOT NULL,
  channel_id BIGINT NOT NULL,
  message_id BIGINT NOT NULL,
  tier       TEXT   NOT NULL,
  PRIMARY KEY (signal_id, channel_id)
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_signal_posts_message
  ON signal_posts(channel_id, message_id);

-- Economic calendar events cached from ForexFactory feeds.
CREATE TABLE IF NOT EXISTS events (
  event_id  TEXT    PRIMARY KEY,
  ts_utc    BIGINT  NOT NULL,
  currency  TEXT    NOT NULL,
  title     TEXT    NOT NULL,
  impact    TEXT    NOT NULL,
  forecast  TEXT,
  previous  TEXT,
  actual    TEXT,
  all_day   INTEGER NOT NULL DEFAULT 0,
  source    TEXT    NOT NULL DEFAULT 'ff',
  synced_at BIGINT  NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_events_ts ON events(ts_utc);

-- Small key/value store (e.g. last calendar digest date).
CREATE TABLE IF NOT EXISTS meta (
  key   TEXT PRIMARY KEY,
  value TEXT
);

-- Research data foundation (docs/research-data.md). Created on demand by `python -m tools.research_data init-schema` or by the opt-in bar archiver
-- (algo-bot/app/research/), NOT by init_db(): deploying the code with runtime.market_data_archive.enabled false creates none of these.

-- The feed's closed bars exactly as published (open_ts = bar open, epoch seconds).
CREATE TABLE IF NOT EXISTS market_bars (
  symbol TEXT NOT NULL, timeframe TEXT NOT NULL, open_ts BIGINT NOT NULL,
  open DOUBLE PRECISION NOT NULL, high DOUBLE PRECISION NOT NULL, low DOUBLE PRECISION NOT NULL, close DOUBLE PRECISION NOT NULL,
  volume DOUBLE PRECISION NOT NULL, ohlc_hash TEXT NOT NULL, source TEXT NOT NULL, ingest_path TEXT NOT NULL,
  normalized BOOLEAN NOT NULL DEFAULT FALSE, revisions INTEGER NOT NULL DEFAULT 0, first_seen_at BIGINT NOT NULL,
  PRIMARY KEY (symbol, timeframe, open_ts)
);
CREATE INDEX IF NOT EXISTS idx_market_bars_tf_ts ON market_bars(timeframe, open_ts);

-- Superseded values of a bar the feed re-published with different values.
CREATE TABLE IF NOT EXISTS market_bar_revisions (
  symbol TEXT NOT NULL, timeframe TEXT NOT NULL, open_ts BIGINT NOT NULL, revision INTEGER NOT NULL,
  open DOUBLE PRECISION NOT NULL, high DOUBLE PRECISION NOT NULL, low DOUBLE PRECISION NOT NULL, close DOUBLE PRECISION NOT NULL,
  volume DOUBLE PRECISION NOT NULL, ohlc_hash TEXT NOT NULL, superseded_at BIGINT NOT NULL,
  PRIMARY KEY (symbol, timeframe, open_ts, revision)
);

-- Per UTC minute quote statistics (spread in price units).
CREATE TABLE IF NOT EXISTS market_quote_minutes (
  symbol TEXT NOT NULL, minute_ts BIGINT NOT NULL, quote_count INTEGER NOT NULL, bid_last DOUBLE PRECISION NOT NULL,
  ask_last DOUBLE PRECISION NOT NULL, spread_min DOUBLE PRECISION NOT NULL, spread_max DOUBLE PRECISION NOT NULL,
  spread_mean DOUBLE PRECISION NOT NULL, first_ts BIGINT NOT NULL, last_ts BIGINT NOT NULL, recorded_at BIGINT NOT NULL,
  PRIMARY KEY (symbol, minute_ts)
);
CREATE INDEX IF NOT EXISTS idx_market_quote_minutes_ts ON market_quote_minutes(minute_ts);

-- Replay-derived (hypothetical) outcome of every published Go opportunity; never mixed with auto_trade_results. Authoritative DDL:
-- algo-bot/app/research/outcome_store.py (columns: geometry, provenance, fill_state, outcome, r_low/r_high, touches, ladder_*, data_quality, assumptions).
CREATE TABLE IF NOT EXISTS opportunity_outcome_labels (
  opportunity_id TEXT NOT NULL, label_set TEXT NOT NULL, strategy TEXT NOT NULL, symbol TEXT NOT NULL, created_at BIGINT NOT NULL,
  thesis_key TEXT NOT NULL, quality_overall DOUBLE PRECISION, quality_model_version INTEGER, quality_components JSONB,
  config_fingerprint TEXT, fill_state TEXT NOT NULL, outcome TEXT NOT NULL, r_low DOUBLE PRECISION, r_high DOUBLE PRECISION,
  touches JSONB, ladder_outcome TEXT, complete BOOLEAN NOT NULL, assumptions JSONB NOT NULL,
  PRIMARY KEY (opportunity_id, label_set)
);

