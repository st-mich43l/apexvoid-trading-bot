"""
store.py — PostgreSQL persistence layer for the XAU Signal bot.

The database is reached through the canonical bootstrap Postgres URL (an
asyncpg/libpq DSN,
default ``postgresql://apexvoid:apexvoid@localhost:5432/signals``). A single
lazily-created connection pool is shared across all asyncio tasks; every helper
acquires a connection for the duration of its work and releases it back.

Tables
------
pips_log
  Append-only record of every pips result the bot auto-edits in the channel
  (e.g. "+80 pips" or "-30 pips"). Queried by ``/trade_pips``
  DM command to produce win/loss summaries.

manual_signals
  Lifecycle tracker for every signal posted manually via the bot's DM interface.
  Stores the original Telegram channel message_id so the bot can later reply to
  (or reference) the exact post when the signal is closed or cancelled.

  Status flow:
    open  ──► closed     (via DM "close <id> +pips" or reply "+pips" to channel post)
        ──► cancelled  (via DM "cancel <id>" or reply "cancel" to channel post)

manual_algo_charts
  Redis OHLC windows (M1/M5/M15/H1) captured at issue, fill, and close for each
  VIP/manual signal so later formula fitting uses the same tape the owner measured.
"""

