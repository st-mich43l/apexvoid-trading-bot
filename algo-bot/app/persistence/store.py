async def store_pips(
  sign: str,
  pips: int,
  message_id: int = None,
  chat_id: str = None,
  signal_id: int = None,
) -> None:
  """Append one pips result to the log.

  Args:
    sign:       ``'+'`` for a winning trade, ``'-'`` for a loss.
    pips:       Absolute pip count (always positive; sign carries direction).
    message_id: Telegram message_id of the edited channel post (optional).
    chat_id:    Telegram chat_id of the channel (optional).
    signal_id:  Linked manual signal primary key (optional).
  """
  async with _connect() as db:
    await db.execute(
      "INSERT INTO pips_log "
      "(ts, sign, pips, message_id, chat_id, signal_id) "
      "VALUES ($1, $2, $3, $4, $5, $6)",
      int(time.time()), sign, pips, message_id,
      str(chat_id) if chat_id else None, signal_id,
    )


async def get_pips_summary(
  start_ts: int,
  end_ts: int,
  symbol: str | None = None,
) -> dict:
  """Aggregate pips results within a Unix timestamp range.

  Returns:
    A dict with keys:
      wins       — number of winning trades in the period.
      win_pips   — total pips gained from winners.
      losses     — number of losing trades in the period.
      loss_pips  — total pips lost from losers (positive integer).
      net        — net pips (win_pips - loss_pips); negative means net loss.
      total      — total number of trades recorded (wins + losses).
  """
  query = (
    "SELECT p.sign, p.pips FROM pips_log p "
    "LEFT JOIN manual_signals s ON s.id = p.signal_id "
    "WHERE p.ts >= $1 AND p.ts <= $2"
  )
  params: list = [start_ts, end_ts]
  if symbol:
    query += " AND s.symbol = $3"
    params.append(symbol.upper())
  async with _connect() as db:
    records = await db.fetch(query, *params)
  rows = [(r["sign"], r["pips"]) for r in records]
  wins   = [(s, p) for s, p in rows if s == '+']
  losses = [(s, p) for s, p in rows if s == '-']
  net    = sum(p if s == '+' else -p for s, p in rows)
  return {
    'wins': len(wins), 'win_pips': sum(p for _, p in wins),
    'losses': len(losses), 'loss_pips': sum(p for _, p in losses),
    'net': net, 'total': len(rows),
  }


async def get_pips_records(
  start_ts: int,
  end_ts: int,
  symbol: str | None = None,
) -> list[dict]:
  """Return manual and broker execution results, oldest first."""
  query = """
    SELECT p.id, p.ts, p.sign, p.pips, p.signal_id,
           s.ts AS signal_ts, s.action, s.entry, s.entry_end,
           s.parent_id, s.setup_type, s.daily_seq, s.symbol,
           s.original_sl, 'manual'::TEXT AS stream,
           ('manual:' || COALESCE(p.signal_id::TEXT, 'pips:' || p.id::TEXT))
             AS trade_key,
           1::BIGINT AS fill_count
    FROM pips_log p
    LEFT JOIN manual_signals s ON s.id = p.signal_id
    WHERE p.ts >= $1 AND p.ts <= $2
  """
  params: list = [start_ts, end_ts]
  if symbol:
    query += " AND s.symbol = $3"
    params.append(symbol.upper())
  query += " ORDER BY p.ts ASC, p.id ASC"
  async with _connect() as db:
    manual_rows = await db.fetch(query, *params)
    algo_query = """
      SELECT r.group_id AS id, r.closed_at AS ts,
             CASE WHEN r.result_pips >= 0 THEN '+' ELSE '-' END AS sign,
             ABS(ROUND(r.result_pips))::INTEGER AS pips,
             NULL::BIGINT AS signal_id,
             MIN(f.filled_at) AS signal_ts,
             MIN(f.direction) AS action,
             AVG(f.entry_price) AS entry,
             AVG(f.entry_price) AS entry_end,
             NULL::BIGINT AS parent_id,
             MIN(f.setup_type) AS setup_type,
             NULL::INTEGER AS daily_seq,
             MIN(f.symbol) AS symbol,
             NULL::DOUBLE PRECISION AS original_sl,
             r.trade_stream AS stream,
             r.trade_key,
             COUNT(*)::BIGINT AS fill_count,
             AVG(f.stop_pips) AS stop_pips,
             r.result_pips / NULLIF(AVG(f.stop_pips), 0) AS r_multiple
      FROM auto_trade_results r
      JOIN auto_trade_fills f ON f.group_id = r.group_id
      WHERE r.closed_at >= $1 AND r.closed_at <= $2
    """
    algo_params: list = [start_ts, end_ts]
    if symbol:
      algo_query += " AND f.symbol = $3"
      algo_params.append(symbol.upper())
    algo_query += (
      " GROUP BY r.group_id, r.closed_at, r.result_pips, "
      "r.trade_stream, r.trade_key ORDER BY r.closed_at ASC, r.group_id ASC"
    )
    algo_rows = await db.fetch(algo_query, *algo_params)

  records = [dict(row) for row in manual_rows]
  for record in records:
    signal_symbol = record.get("symbol") or "XAU"
    entry = record.get("entry")
    entry_end = record.get("entry_end")
    stop = record.get("original_sl")
    if entry is None or stop is None:
      continue
    reference = (
      entry_end if record.get("action") == "BUY" and entry_end is not None
      else entry
    )
    stop_pips = abs(float(reference) - float(stop)) / pip_for(signal_symbol)
    record["stop_pips"] = stop_pips
    record["r_multiple"] = (
      (record["pips"] if record["sign"] == "+" else -record["pips"])
      / stop_pips
      if stop_pips > 0 else None
    )
  records.extend(dict(row) for row in algo_rows)
  return sorted(records, key=lambda row: (row["ts"], str(row["id"])))


async def record_auto_trade_event(event: dict) -> None:
  """Persist fill attribution and terminal broker results idempotently."""
  event_type = str(event.get("type") or "")
  if event_type in {"opened", "add", "manual_opened", "order_filled"}:
    await _record_auto_trade_fill(event)
  elif event_type in {"group_result", "position_closed", "manual_closed"}:
    await _record_auto_trade_result(event)


def _resolve_auto_trade_stream(event: dict) -> str:
  stream = str(event.get("stream") or "").strip()
  if stream in {"algo_auto", "algo_manual"}:
    return stream
  # TradePlan events omit stream; attribute them as autonomous algo.
  candidate = str(event.get("candidate_id") or "")
  group_id = str(event.get("group_id") or "")
  if candidate.startswith("v8:") or group_id.startswith("v8:"):
    return "algo_auto"
  setup = str(event.get("setup") or "").strip().lower()
  if setup == "manual algo":
    return "algo_manual"
  if event.get("position_id") is not None and (
    event.get("setup") or event.get("direction")
  ):
    return "algo_auto"
  return stream


def _resolve_fill_stop_pips(event: dict, symbol: str) -> float | None:
  raw = event.get("stop_pips")
  if raw is not None:
    try:
      value = float(raw)
    except (TypeError, ValueError):
      value = None
    else:
      if value > 0:
        return value
  stop_loss = event.get("stop_loss")
  entry = event.get("price")
  if stop_loss is None or entry is None:
    return None
  try:
    return abs(float(entry) - float(stop_loss)) / pip_for(symbol)
  except (TypeError, ValueError, ZeroDivisionError):
    return None


async def _record_auto_trade_fill(event: dict) -> None:
  position_id = event.get("position_id")
  stream = _resolve_auto_trade_stream(event)
  if position_id is None or stream not in {"algo_auto", "algo_manual"}:
    return
  group_id = str(event.get("group_id") or position_id)
  trade_key = f"algo:{group_id}"
