async def close_leg(
  row_id: int,
  pips: int,
  frac: float | None = None,
) -> dict | None:
  """Book one scale-out leg and close the signal when no size remains."""
  snapshot_close: tuple[int, int, str] | None = None
  async with _connect() as db:
    async with db.transaction():
      row = await db.fetchrow(
        "SELECT * FROM manual_signals WHERE id = $1 AND status = 'open' "
        "FOR UPDATE",
        row_id,
      )
      if row is None:
        return None

      legs = json.loads(row["legs"] or "[]")
      used = sum(float(leg["frac"]) for leg in legs)
      remaining = max(0.0, 1.0 - used)
      close_frac = remaining if frac is None else frac
      result_base = {
        "id": row["id"],
        "channel_message_id": row["channel_message_id"],
        "daily_seq": row["daily_seq"],
        "symbol": row["symbol"],
        "visibility": row["visibility"],
      }
      if close_frac <= 0 or close_frac > remaining + _LEG_EPSILON:
        return {
          **result_base,
          "error": "exceeds_remaining",
          "remaining": remaining,
        }

      now = int(time.time())
      legs.append({"frac": close_frac, "pips": pips, "ts": now})
      new_remaining = 1.0 - sum(float(leg["frac"]) for leg in legs)
      # Journal /trade_stats uses the highest TP/pips reached, not a
      # volume-fraction weighted blend that dilutes booked targets with a
      # later BE residual.
      achieved = legs_achieved_pips(legs)
      if new_remaining <= _LEG_EPSILON:
        await db.execute(
          "UPDATE manual_signals SET status = 'closed', result_pips = $1, "
          "closed_at = $2, legs = $3 WHERE id = $4 AND status = 'open'",
          achieved, now, json.dumps(legs), row_id,
        )
        snapshot_close = (int(row_id), now, str(row["symbol"] or "XAU"))
        result = {
          **result_base,
          "closed": True,
          "net": achieved,
          "remaining": 0.0,
          "frac": close_frac,
        }
      else:
        await db.execute(
          "UPDATE manual_signals SET legs = $1 "
          "WHERE id = $2 AND status = 'open'",
          json.dumps(legs), row_id,
        )
        result = {
          **result_base,
          "closed": False,
          "net": achieved,
          "remaining": new_remaining,
          "frac": close_frac,
        }
  if snapshot_close is not None:
    await _safe_snapshot_manual_chart(
      signal_id=snapshot_close[0],
      event="closed",
      ts=snapshot_close[1],
      symbol=snapshot_close[2],
    )
  return result


async def finalize_manual_group(
  row_id: int,
  result_pips: int,
) -> dict | None:
  """Close a manual /algo signal using AutoTradeEngine.cs's own final,
  authoritative group result (its ``group_result`` event's
  ``group_realized_pips``), bypassing ``close_leg``'s frac-accumulation
  ledger entirely.

  A manual /algo signal can be several independent entry legs (shallow/
  mid/deep, each its own broker position filled at its own price) closing
  together off one shared owner stop. For **losses**, prefer
  ``group_realized_pips`` (AutoTradeEngine.cs's volume-weighted total
  across independently-priced entry legs — 2026-08-19: a 3-leg SELL must
  not report -26 when the true blended loss was -47). For **wins**,
  channel TP cards already booked via ``close_leg`` must not be downgraded
  on the close line — ``legs_achieved_pips`` keeps the highest TP reached
  (e.g. TP4 +160 from the deep fill) even when ``group_realized_pips``
  from the last shallow leg prints +130.
  """
  now = int(time.time())
  snapshot_close: tuple[int, int, str] | None = None
  async with _connect() as db:
    async with db.transaction():
      row = await db.fetchrow(
        "SELECT * FROM manual_signals WHERE id = $1 AND status = 'open' "
        "FOR UPDATE",
        row_id,
      )
      if row is None:
        return None
      legs = json.loads(row["legs"] or "[]")
      legs.append({"frac": 1.0, "pips": result_pips, "ts": now})
      # Channel TP cards already booked the highest target reached; the
      # close line must never report a lower number than those legs (e.g.
      # group_realized_pips from the last shallow leg after TP4 printed
      # +160 from the deep fill).
      achieved = legs_achieved_pips(legs)
      await db.execute(
        "UPDATE manual_signals SET status = 'closed', result_pips = $1, "
        "closed_at = $2, legs = $3 WHERE id = $4 AND status = 'open'",
        achieved, now, json.dumps(legs), row_id,
      )
      snapshot_close = (int(row_id), now, str(row["symbol"] or "XAU"))
  if snapshot_close is not None:
    await _safe_snapshot_manual_chart(
      signal_id=snapshot_close[0],
      event="closed",
      ts=snapshot_close[1],
      symbol=snapshot_close[2],
    )
  return {
    "id": row["id"],
    "channel_message_id": row["channel_message_id"],
    "daily_seq": row["daily_seq"],
    "symbol": row["symbol"],
    "visibility": row["visibility"],
    "closed": True,
    "net": achieved,
    "remaining": 0.0,
    "frac": 1.0,
  }


