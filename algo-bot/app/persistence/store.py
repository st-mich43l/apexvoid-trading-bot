async def set_execution_fill(
  signal_id: int,
  *,
  broker_position_id: int,
  broker_fill_price: float,
) -> dict | None:
  """Record a manual-algo limit order's real broker fill.

  Called once per FILLED ENTRY LEG (from the reconcile loop) when
  AutoTradeEngine.cs's fill adoption reconstructs a position and publishes
  its "manual_opened" event - a manual /algo signal can be several
  independent entry legs (the shallow/mid/deep split), so this fires more
  than once for the same signal_id.

  ``broker_fill_price`` keeps the **shallow** filled entry (the approved
  worst-case risk reference: lower for SELL, higher for BUY). Mid/deep
  fills retain their own prices in executor state and lifecycle events for
  actual weighted P&L; this one-column signal fallback must never shrink the
  owner stop distance merely because a deeper clip filled. The position id
  still keeps the first fill via COALESCE (owner close routes by intent
  group, not this column).

  Returns the updated row, or ``None`` if ``signal_id`` does not exist.
  """
  async with _connect() as db:
    row = await db.fetchrow(
      """
      UPDATE manual_signals SET
        execution_status = 'filled',
        algo_armed = TRUE,
        trade_stream = 'algo_manual',
        broker_position_id = COALESCE(broker_position_id, $1),
        broker_fill_price = CASE
          WHEN broker_fill_price IS NULL THEN $2
          WHEN UPPER(action) = 'SELL' AND $2 < broker_fill_price THEN $2
          WHEN UPPER(action) = 'BUY' AND $2 > broker_fill_price THEN $2
          ELSE broker_fill_price
        END
      WHERE id = $3
      RETURNING *
      """,
      str(broker_position_id), broker_fill_price, signal_id,
    )
  decoded = _decode_signal(row) if row else None
  if decoded is not None:
    await _safe_snapshot_manual_chart(
      signal_id=int(signal_id),
      event="filled",
      ts=int(time.time()),
      symbol=str(decoded.get("symbol") or "XAU"),
    )
  return decoded


async def get_signal_by_execution_intent_id(intent_token: str) -> dict | None:
  """Look up a manual signal by its ``execution_intent_id``.

  Tolerates the truncated identity cTrader comments carry: comment fields
  are capped at 100 chars broker-side, so AutoTradeEngine.cs embeds only
  ``CandidateToken(intent_id)`` (the first 10 characters) in a manual-algo
  position/order comment — the same truncation convention every other
  candidate type in this codebase already accepts for comment-based
  identity matching. Matching by prefix means either the full
  ``execution_intent_id`` or that truncated token resolves the same row.
  On the rare (and, for this single-owner bot, extremely unlikely) case of
  two signals sharing a 10-character prefix, the most recently created
  match wins.
  """
  async with _connect() as db:
    row = await db.fetchrow(
      "SELECT * FROM manual_signals WHERE execution_intent_id LIKE $1 || '%' "
      "ORDER BY id DESC LIMIT 1",
      intent_token[:10],
    )
  return _decode_signal(row) if row else None


